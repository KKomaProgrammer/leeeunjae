self.addEventListener('install', (event) => {
  event.waitUntil(self.skipWaiting());
});

self.addEventListener('activate', (event) => {
  event.waitUntil(self.clients.claim());
});

self.addEventListener('push', (event) => {
  let payload = {};
  try {
    payload = event.data?.json() || {};
  } catch {
    payload = { title: '새 게시물이 등록되었습니다', body: event.data?.text() || '' };
  }
  const title = payload.title || '새 게시물이 등록되었습니다';
  const body = payload.body || '눌러서 숙제 이미지를 확인하세요.';
  const data = { url: payload.url || '/' };
  event.waitUntil((async () => {
    try {
      const options = {
        body,
        image: payload.imageUrl,
        icon: '/icon.svg',
        badge: '/icon.svg',
        tag: payload.tag || 'class-board',
        renotify: true,
        timestamp: Date.now(),
        data,
      };
      if (payload.actions !== false) {
        options.actions = [
          { action: 'share', title: '공유' },
          { action: 'download', title: '다운로드' },
        ];
      }
      await self.registration.showNotification(title, options);
    } catch (error) {
      console.error('Rich notification failed; using basic notification', error);
      await self.registration.showNotification(title, { body, icon: '/icon.svg', data });
    }
  })());
});

self.addEventListener('notificationclick', (event) => {
  event.notification.close();
  const targetUrl = new URL(event.notification.data?.url || '/', self.location.origin);
  // Notifications are generated by the Cloudflare backend; open them in this installed frontend.
  if (targetUrl.origin === 'https://eunjae.pages.dev' && targetUrl.pathname === '/') {
    targetUrl.protocol = self.location.protocol;
    targetUrl.host = self.location.host;
  }
  if (event.action === 'share' || event.action === 'download') {
    targetUrl.searchParams.set('notificationAction', event.action);
  }
  const target = targetUrl.toString();
  event.waitUntil((async () => {
    // Android의 백그라운드 PWA에 navigate()만 하면 화면은 열리지 않은 채
    // 내용만 바뀔 수 있다. 알림 클릭 권한 안에서 openWindow()를 먼저 호출하면
    // 설치 앱 또는 기존 창을 전면으로 가져오며, 반환된 클라이언트도 다시 focus한다.
    try {
      const opened = await self.clients.openWindow(target);
      if (opened) return opened.focus();
    } catch (error) {
      console.error('Opening notification window failed; focusing an existing client', error);
    }
    const clients = await self.clients.matchAll({ type: 'window', includeUncontrolled: true });
    const sameOrigin = clients.filter((client) => {
      try {
        return new URL(client.url).origin === self.location.origin;
      } catch {
        return false;
      }
    });
    const existing = sameOrigin.find((client) => client.focused) ||
      sameOrigin.find((client) => client.visibilityState === 'visible') || sameOrigin[0];
    if (!existing) return undefined;
    const navigated = await existing.navigate(target);
    return (navigated || existing).focus();
  })());
});

